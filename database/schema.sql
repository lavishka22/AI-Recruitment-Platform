create table if not exists job_descriptions (
    id bigint generated by default as identity primary key,
    title text not null,
    description text not null,
    required_skills jsonb default '[]'::jsonb,
    created_at timestamptz default now(),
    updated_at timestamptz default now()
);

create table if not exists candidate_evaluations (
    id bigint generated by default as identity primary key,
    candidate_id bigint not null references candidates(id) on delete cascade,
    job_description_id bigint not null references job_descriptions(id) on delete cascade,

    resume_match_score numeric default 0,
    project_relevance_score numeric default 0,
    research_relevance_score numeric default 0,
    cgpa_score numeric default 0,
    logical_aptitude_score numeric default 0,
    coding_test_score numeric default 0,
    overall_score numeric default 0,

    matched_skills jsonb default '[]'::jsonb,
    missing_skills jsonb default '[]'::jsonb,
    recommendation text,
    explanation text,

    created_at timestamptz default now(),
    updated_at timestamptz default now(),

    unique(candidate_id, job_description_id)
);


