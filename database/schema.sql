create table if not exists candidates (
    id bigint generated by default as identity primary key,
    s_no integer,
    name text not null,
    email text not null unique,
    college text,
    branch text,
    cgpa numeric,
    best_ai_project text,
    research_work text,
    github text,
    resume text,
    test_la numeric,
    test_code numeric,
    status text default 'uploaded',
    created_at timestamptz default now(),
    updated_at timestamptz default now()
);

create table if not exists github_analyses (
    id bigint generated by default as identity primary key,

    candidate_id bigint not null
        references candidates(id)
        on delete cascade,

    github_username text,
    profile_url text,

    public_repositories integer default 0,
    analyzed_repositories integer default 0,
    followers integer default 0,
    following integer default 0,

    total_stars integer default 0,
    total_forks integer default 0,
    recent_commits integer default 0,
    repositories_with_readme integer default 0,

    languages jsonb default '{}'::jsonb,
    top_repositories jsonb default '[]'::jsonb,

    repository_quality_score numeric default 0,
    documentation_score numeric default 0,
    activity_score numeric default 0,
    diversity_score numeric default 0,
    github_score numeric default 0,

    strengths jsonb default '[]'::jsonb,
    concerns jsonb default '[]'::jsonb,
    explanation text,

    status text default 'pending',
    analyzed_at timestamptz,

    created_at timestamptz default now(),
    updated_at timestamptz default now(),

    unique(candidate_id)
);

